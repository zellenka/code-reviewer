import { describe, expect, it } from 'vitest';
import { addedFileDiff } from '../diff/parse';
import type { FileDiff } from '../diff/types';
import { filterFiles, isSecretPath } from './filter';
import { createRedactor, redactFiles, redactText } from './redact';

const file = (
  path: string,
  content = 'const x = 1;\n',
  extra: Partial<FileDiff> = {},
): FileDiff => ({
  ...addedFileDiff(path, content),
  ...extra,
});

describe('filterFiles', () => {
  it('skips built-in noise, secrets, binaries, deletions and config globs', () => {
    const files = [
      file('src/app.ts'),
      file('pnpm-lock.yaml'),
      file('packages/x/package-lock.json'),
      file('dist/app.js'),
      file('web/build/index.html'),
      file('vendor/lib.min.js'),
      file('src/__snapshots__/a.test.ts.snap'),
      file('.env'),
      file('config/.env.production'),
      file('certs/server.PEM'),
      file('keys/id_rsa'),
      file('src/gen.ts', '// @generated by protoc\nexport {}\n'),
      file('src/big.js', `${'a'.repeat(4000)}\n`),
      file('img.png', '', { binary: true, hunks: [] }),
      file('old.ts', '', { status: 'deleted' }),
      file('src/api.generated.ts'),
      file('docs/guide.md'),
      file('renamed-only.ts', '', { status: 'renamed', hunks: [] }),
    ];
    const { files: kept, skipped } = filterFiles(files, ['**/*.generated.ts', 'docs/']);
    expect(kept.map((f) => f.path)).toEqual(['src/app.ts']);
    const reasons = Object.fromEntries(skipped.map((s) => [s.path, s.reason]));
    expect(reasons).toEqual({
      'pnpm-lock.yaml': 'lockfile',
      'packages/x/package-lock.json': 'lockfile',
      'dist/app.js': 'buildOutput',
      'web/build/index.html': 'buildOutput',
      'vendor/lib.min.js': 'minified',
      'src/__snapshots__/a.test.ts.snap': 'snapshot',
      '.env': 'secret',
      'config/.env.production': 'secret',
      'certs/server.PEM': 'secret',
      'keys/id_rsa': 'secret',
      'src/gen.ts': 'generated',
      'src/big.js': 'minified',
      'img.png': 'binary',
      'old.ts': 'deleted',
      'src/api.generated.ts': 'configIgnore',
      'docs/guide.md': 'configIgnore',
      'renamed-only.ts': 'noChanges',
    });
  });

  it('a deleted secret file is reported as secret, and secrets cannot be un-ignored', () => {
    expect(filterFiles([file('.env', '', { status: 'deleted' })]).skipped[0]!.reason).toBe(
      'secret',
    );
    expect(isSecretPath('a/b/.env.local')).toBe(true);
    expect(isSecretPath('src/env.ts')).toBe(false);
  });

  it('keeps files that only delete lines', () => {
    const f: FileDiff = {
      path: 'a.ts',
      status: 'modified',
      binary: false,
      hunks: [
        {
          oldStart: 1,
          oldLines: 2,
          newStart: 1,
          newLines: 1,
          lines: [
            { kind: 'ctx', text: 'a', oldLine: 1, newLine: 1 },
            { kind: 'del', text: 'check()', oldLine: 2 },
          ],
        },
      ],
    };
    expect(filterFiles([f]).files).toHaveLength(1);
  });
});

describe('redaction', () => {
  it('redacts known secret formats and keeps line structure', () => {
    const input = [
      'const id = "AKIAIOSFODNN7EXAMPLE";',
      'aws_secret_access_key = "wJalrXUtnFEMI/K7MDENG/bPxRfiCYEXAMPLEKEY"',
      'token: ghp_abcdefghijklmnopqrstuvwxyz0123456789',
      'const k = "sk-ant-api03-abcdefghijklmnopqrstuvwxyz";',
      'url = "postgres://admin:s3cretPass@db:5432/x"',
      'const password = "hunter2hunter2";',
      'const harmless = "hello world";',
    ].join('\n');
    const { text, count } = redactText(input);
    expect(count).toBe(6);
    expect(text.split('\n')).toHaveLength(7);
    expect(text).not.toMatch(
      /AKIAIOSFODNN7EXAMPLE|wJalrXUtnFEMI|ghp_abc|sk-ant-api03|s3cretPass|hunter2/,
    );
    expect(text).toContain('const password = "[REDACTED:secret]";');
    expect(text).toContain('postgres://admin:[REDACTED:connection-string-password]@db');
    expect(text).toContain('const harmless = "hello world";');
  });

  it('redacts PEM private key blocks line by line', () => {
    const r = createRedactor();
    const out = [
      '-----BEGIN RSA PRIVATE KEY-----',
      'MIIEowIBAAKCAQEA1234',
      'abcdEFGH5678',
      '-----END RSA PRIVATE KEY-----',
      'after',
    ].map((l) => r.line(l));
    expect(out).toEqual([
      '-----BEGIN RSA PRIVATE KEY-----',
      '[REDACTED:private-key]',
      '[REDACTED:private-key]',
      '-----END RSA PRIVATE KEY-----',
      'after',
    ]);
  });

  it('counts PEM body lines, keeps blank lines and leaves text around the block alone', () => {
    const input = [
      'const before = 1;',
      'const key =',
      '  "-----BEGIN PRIVATE KEY-----\\n" +',
      '  "MIIEvQIBADANBgkqhkiG9w0BAQEFAASC\\n" +',
      '',
      '  "abcdEFGH5678\\n" +',
      '  "-----END PRIVATE KEY-----\\n";',
      'const after = 2;',
    ];
    const { text, count } = redactText(input.join('\n'));
    expect(count).toBe(2);
    expect(text.split('\n')).toEqual([
      input[0],
      input[1],
      input[2],
      '[REDACTED:private-key]',
      '',
      '[REDACTED:private-key]',
      input[6],
      input[7],
    ]);
  });

  it('reset() leaves a private key block', () => {
    const r = createRedactor();
    r.line('-----BEGIN PRIVATE KEY-----');
    expect(r.line('MIIEvQIBADANBgkqhkiG9w0BAQEFAASC')).toBe('[REDACTED:private-key]');
    r.reset();
    expect(r.line('const x = 1;')).toBe('const x = 1;');
    expect(r.count).toBe(1);
  });

  it('redactFiles tracks a key block inside a hunk and resets between hunks', () => {
    const f: FileDiff = {
      path: 'k.ts',
      status: 'modified',
      binary: false,
      hunks: [
        {
          oldStart: 1,
          oldLines: 0,
          newStart: 1,
          newLines: 2,
          lines: [
            { kind: 'add', text: '-----BEGIN PRIVATE KEY-----', newLine: 1 },
            { kind: 'add', text: 'MIIEvQIBADANBgkqhkiG9w0BAQEFAASC', newLine: 2 },
          ],
        },
        {
          oldStart: 40,
          oldLines: 1,
          newStart: 42,
          newLines: 1,
          lines: [{ kind: 'ctx', text: 'const x = 1;', oldLine: 40, newLine: 42 }],
        },
      ],
    };
    const { files, count } = redactFiles([f]);
    expect(count).toBe(1);
    expect(files[0]!.hunks.map((h) => h.lines.map((l) => l.text))).toEqual([
      ['-----BEGIN PRIVATE KEY-----', '[REDACTED:private-key]'],
      ['const x = 1;'],
    ]);
  });

  it('redacts a private key stored on one line (JSON-escaped)', () => {
    const input = [
      '{',
      '  "type": "service_account",',
      '  "private_key": "-----BEGIN PRIVATE KEY-----\\nMIIEvQIBADANBgkqhkiG9w0BAQEFAASCBKcwggSj\\n-----END PRIVATE KEY-----\\n",',
      '  "client_email": "x@y.iam.gserviceaccount.com"',
      '}',
    ];
    const { text, count } = redactText(input.join('\n'));
    expect(count).toBe(1);
    expect(text.split('\n')).toEqual([
      input[0],
      input[1],
      '  "private_key": "-----BEGIN PRIVATE KEY-----[REDACTED:private-key]-----END PRIVATE KEY-----\\n",',
      input[3],
      input[4],
    ]);
  });

  it('redacts a private key stored on one line (plain)', () => {
    const r = createRedactor();
    expect(
      r.line(
        'KEY=-----BEGIN RSA PRIVATE KEY----- MIIEowIBAAKCAQEA1234 abcdEFGH5678 -----END RSA PRIVATE KEY-----',
      ),
    ).toBe(
      'KEY=-----BEGIN RSA PRIVATE KEY-----[REDACTED:private-key]-----END RSA PRIVATE KEY-----',
    );
    expect(r.count).toBe(1);
    // The block is closed: the next line is ordinary code.
    expect(r.line('const x = 1;')).toBe('const x = 1;');
  });

  it('redacts two private keys on one line', () => {
    const { text, count } = redactText(
      'a="-----BEGIN PRIVATE KEY-----\\nMIIEvQIBADANBgkq\\n-----END PRIVATE KEY-----" b="-----BEGIN EC PRIVATE KEY-----\\nMHcCAQEEIIrYSSNQ\\n-----END EC PRIVATE KEY-----"',
    );
    expect(count).toBe(2);
    expect(text).toBe(
      'a="-----BEGIN PRIVATE KEY-----[REDACTED:private-key]-----END PRIVATE KEY-----" b="-----BEGIN EC PRIVATE KEY-----[REDACTED:private-key]-----END EC PRIVATE KEY-----"',
    );
  });

  it('redacts key material that shares a line with the BEGIN or END marker', () => {
    const r = createRedactor();
    const out = [
      'key: "-----BEGIN PRIVATE KEY-----\\nMIIEvQIBADANBgkqhkiG9w0BAQEFAASC',
      'abcdEFGH5678',
      'TAILOFKEYMATERIAL99\\n-----END PRIVATE KEY-----"',
      'after',
    ].map((l) => r.line(l));
    expect(out).toEqual([
      'key: "-----BEGIN PRIVATE KEY-----[REDACTED:private-key]',
      '[REDACTED:private-key]',
      '[REDACTED:private-key]-----END PRIVATE KEY-----"',
      'after',
    ]);
    expect(r.count).toBe(3);
  });

  it('redactFiles redacts a one-line private key in hunks and content', () => {
    const line =
      '  "private_key": "-----BEGIN PRIVATE KEY-----\\nMIIEvQIBADANBgkqhkiG9w0BAQEFAASCBKcwggSj\\n-----END PRIVATE KEY-----\\n",';
    const f = file('sa.json', `{\n${line}\n  "a": 1\n}\n`);
    const { files, count } = redactFiles([f]);
    expect(count).toBe(1);
    expect(JSON.stringify(files)).not.toContain('MIIEvQIBADANBgkqhkiG9w0BAQEFAASCBKcwggSj');
    expect(files[0]!.hunks[0]!.lines).toHaveLength(f.hunks[0]!.lines.length);
    expect(files[0]!.hunks[0]!.lines[2]!.text).toBe('  "a": 1');
    expect(files[0]!.newContent!.split('\n')).toHaveLength(f.newContent!.split('\n').length);
  });

  it('a hunk starting inside a private key block is still redacted', () => {
    const content = [
      'const key = `',
      '-----BEGIN PRIVATE KEY-----',
      'MIIEvQIBADANBgkqhkiG9w0BAQEFAASC',
      'CHANGEDLINEOFKEYMATERIAL123',
      '-----END PRIVATE KEY-----',
      '`;',
      '',
    ].join('\n');
    const f: FileDiff = {
      path: 'k.ts',
      status: 'modified',
      binary: false,
      newContent: content,
      hunks: [
        {
          oldStart: 4,
          oldLines: 1,
          newStart: 4,
          newLines: 1,
          lines: [
            { kind: 'del', text: 'OLDLINEOFKEYMATERIAL', oldLine: 4 },
            { kind: 'add', text: 'CHANGEDLINEOFKEYMATERIAL123', newLine: 4 },
          ],
        },
      ],
    };
    const { files } = redactFiles([f]);
    expect(JSON.stringify(files)).not.toContain('CHANGEDLINEOFKEYMATERIAL123');
  });

  it('high-entropy redaction is opt-in', () => {
    const line = 'const t = "Zx9Qp2Lm7Rt4Vb8Nc1Kd6Wf3Hy5Js0Ga";';
    expect(redactText(line).text).toBe(line);
    expect(redactText(line, { highEntropy: true }).text).toContain('[REDACTED:high-entropy]');
    expect(
      redactText('const camelCaseIdentifierThatIsLong = 1;', { highEntropy: true }).count,
    ).toBe(0);
  });

  it('redactFiles changes hunks and content without mutating the input', () => {
    const f = file('a.ts', 'const id = "AKIAIOSFODNN7EXAMPLE";\n');
    const { files, count } = redactFiles([f]);
    expect(count).toBe(1);
    expect(files[0]!.hunks[0]!.lines[0]!.text).toContain('[REDACTED:aws-access-key]');
    expect(files[0]!.newContent).toContain('[REDACTED:aws-access-key]');
    expect(f.hunks[0]!.lines[0]!.text).toContain('AKIA');
  });
});

