import { describe, expect, it } from 'vitest';
import { addedFileDiff } from '../diff/parse';
import type { FileDiff } from '../diff/types';
import { filterFiles, isSecretPath } from './filter';
import { createRedactor, redactFiles, redactText } from './redact';

const file = (
  path: string,
  content = 'const x = 1;\n',
  extra: Partial<FileDiff> = {},
): FileDiff => ({
  ...addedFileDiff(path, content),
  ...extra,
});

describe('filterFiles', () => {
  it('skips built-in noise, secrets, binaries, deletions and config globs', () => {
    const files = [
      file('src/app.ts'),
      file('pnpm-lock.yaml'),
      file('packages/x/package-lock.json'),
      file('dist/app.js'),
      file('web/build/index.html'),
      file('vendor/lib.min.js'),
      file('src/__snapshots__/a.test.ts.snap'),
      file('.env'),
      file('config/.env.production'),
      file('certs/server.PEM'),
      file('keys/id_rsa'),
      file('src/gen.ts', '// @generated by protoc\nexport {}\n'),
      file('src/big.js', `${'a'.repeat(4000)}\n`),
      file('img.png', '', { binary: true, hunks: [] }),
      file('old.ts', '', { status: 'deleted' }),
      file('src/api.generated.ts'),
      file('docs/guide.md'),
      file('renamed-only.ts', '', { status: 'renamed', hunks: [] }),
    ];
    const { files: kept, skipped } = filterFiles(files, ['**/*.generated.ts', 'docs/']);
    expect(kept.map((f) => f.path)).toEqual(['src/app.ts']);
    const reasons = Object.fromEntries(skipped.map((s) => [s.path, s.reason]));
    expect(reasons).toEqual({
      'pnpm-lock.yaml': 'lockfile',
      'packages/x/package-lock.json': 'lockfile',
      'dist/app.js': 'buildOutput',
      'web/build/index.html': 'buildOutput',
      'vendor/lib.min.js': 'minified',
      'src/__snapshots__/a.test.ts.snap': 'snapshot',
      '.env': 'secret',
      'config/.env.production': 'secret',
      'certs/server.PEM': 'secret',
      'keys/id_rsa': 'secret',
      'src/gen.ts': 'generated',
      'src/big.js': 'minified',
      'img.png': 'binary',
      'old.ts': 'deleted',
      'src/api.generated.ts': 'configIgnore',
      'docs/guide.md': 'configIgnore',
      'renamed-only.ts': 'noChanges',
    });
  });

  it('a deleted secret file is reported as secret, and secrets cannot be un-ignored', () => {
    expect(filterFiles([file('.env', '', { status: 'deleted' })]).skipped[0]!.reason).toBe(
      'secret',
    );
    expect(isSecretPath('a/b/.env.local')).toBe(true);
    expect(isSecretPath('src/env.ts')).toBe(false);
  });

  it('keeps files that only delete lines', () => {
    const f: FileDiff = {
      path: 'a.ts',
      status: 'modified',
      binary: false,
      hunks: [
        {
          oldStart: 1,
          oldLines: 2,
          newStart: 1,
          newLines: 1,
          lines: [
            { kind: 'ctx', text: 'a', oldLine: 1, newLine: 1 },
            { kind: 'del', text: 'check()', oldLine: 2 },
          ],
        },
      ],
    };
    expect(filterFiles([f]).files).toHaveLength(1);
  });
});

describe('redaction', () => {
  it('redacts known secret formats and keeps line structure', () => {
    const input = [
      'const id = "AKIAIOSFODNN7EXAMPLE";',
      'aws_secret_access_key = "wJalrXUtnFEMI/K7MDENG/bPxRfiCYEXAMPLEKEY"',
      'token: ghp_abcdefghijklmnopqrstuvwxyz0123456789',
      'const k = "sk-ant-api03-abcdefghijklmnopqrstuvwxyz";',
      'url = "postgres://admin:s3cretPass@db:5432/x"',
      'const password = "hunter2hunter2";',
      'const harmless = "hello world";',
    ].join('\n');
    const { text, count } = redactText(input);
    expect(count).toBe(6);
    expect(text.split('\n')).toHaveLength(7);
    expect(text).not.toMatch(
      /AKIAIOSFODNN7EXAMPLE|wJalrXUtnFEMI|ghp_abc|sk-ant-api03|s3cretPass|hunter2/,
    );
    expect(text).toContain('const password = "[REDACTED:secret]";');
    expect(text).toContain('postgres://admin:[REDACTED:connection-string-password]@db');
    expect(text).toContain('const harmless = "hello world";');
  });

  it('redacts PEM private key blocks line by line', () => {
    const r = createRedactor();
    const out = [
      '-----BEGIN RSA PRIVATE KEY-----',
      'MIIEowIBAAKCAQEA1234',
      'abcdEFGH5678',
      '-----END RSA PRIVATE KEY-----',
      'after',
    ].map((l) => r.line(l));
    expect(out).toEqual([
      '-----BEGIN RSA PRIVATE KEY-----',
      '[REDACTED:private-key]',
      '[REDACTED:private-key]',
      '-----END RSA PRIVATE KEY-----',
      'after',
    ]);
  });

  it('a hunk starting inside a private key block is still redacted', () => {
    const content = [
      'const key = `',
      '-----BEGIN PRIVATE KEY-----',
      'MIIEvQIBADANBgkqhkiG9w0BAQEFAASC',
      'CHANGEDLINEOFKEYMATERIAL123',
      '-----END PRIVATE KEY-----',
      '`;',
      '',
    ].join('\n');
    const f: FileDiff = {
      path: 'k.ts',
      status: 'modified',
      binary: false,
      newContent: content,
      hunks: [
        {
          oldStart: 4,
          oldLines: 1,
          newStart: 4,
          newLines: 1,
          lines: [
            { kind: 'del', text: 'OLDLINEOFKEYMATERIAL', oldLine: 4 },
            { kind: 'add', text: 'CHANGEDLINEOFKEYMATERIAL123', newLine: 4 },
          ],
        },
      ],
    };
    const { files } = redactFiles([f]);
    expect(JSON.stringify(files)).not.toContain('CHANGEDLINEOFKEYMATERIAL123');
  });

  it('high-entropy redaction is opt-in', () => {
    const line = 'const t = "Zx9Qp2Lm7Rt4Vb8Nc1Kd6Wf3Hy5Js0Ga";';
    expect(redactText(line).text).toBe(line);
    expect(redactText(line, { highEntropy: true }).text).toContain('[REDACTED:high-entropy]');
    expect(
      redactText('const camelCaseIdentifierThatIsLong = 1;', { highEntropy: true }).count,
    ).toBe(0);
  });

  it('redactFiles changes hunks and content without mutating the input', () => {
    const f = file('a.ts', 'const id = "AKIAIOSFODNN7EXAMPLE";\n');
    const { files, count } = redactFiles([f]);
    expect(count).toBe(1);
    expect(files[0]!.hunks[0]!.lines[0]!.text).toContain('[REDACTED:aws-access-key]');
    expect(files[0]!.newContent).toContain('[REDACTED:aws-access-key]');
    expect(f.hunks[0]!.lines[0]!.text).toContain('AKIA');
  });
});
